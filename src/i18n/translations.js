const ALIASES = {
    "zh-Hant": "zh-TW",
    "zh-HK": "zh-TW",
    "zh-MO": "zh-TW",
    "zh-Hans": "zh",
    "pt-BR": "pt",
    "pt-PT": "pt",
};

export const DEFAULT_LANG = "en";
const STORAGE_KEY = "connectnet-language";

export function detectLanguage() {
    let saved = null;
    try {
        saved = localStorage.getItem(STORAGE_KEY);
    } catch (error) {
        saved = null;
    }
    if (saved && TRANSLATIONS[saved]) return saved;

    const candidates =
        navigator.languages && navigator.languages.length
            ? navigator.languages
            : [navigator.language || ""];

    for (const code of candidates) {
        if (!code) continue;
        if (TRANSLATIONS[code]) return code;
        if (ALIASES[code] && TRANSLATIONS[ALIASES[code]]) {
            return ALIASES[code];
        }
        const base = code.split("-")[0];
        if (TRANSLATIONS[base]) return base;
    }

    return DEFAULT_LANG;
}

export function rememberLanguage(lang) {
    try {
        localStorage.setItem(STORAGE_KEY, lang);
    } catch (error) {
        /* El navegador puede bloquear el almacenamiento. */
    }
}

export function applyLanguage(lang = detectLanguage()) {
    const texts = TRANSLATIONS[lang] || TRANSLATIONS[DEFAULT_LANG];
    const active = TRANSLATIONS[lang] ? lang : DEFAULT_LANG;

    document.documentElement.lang = active;
    document.documentElement.setAttribute("data-lang", active);

    document.querySelectorAll("[data-i18n]").forEach((element) => {
        const key = element.getAttribute("data-i18n");
        if (texts[key] !== undefined) element.textContent = texts[key];
    });

    document.querySelectorAll("[data-i18n-html]").forEach((element) => {
        const key = element.getAttribute("data-i18n-html");
        if (texts[key] !== undefined) element.innerHTML = texts[key];
    });

    if (texts["meta.title"]) document.title = texts["meta.title"];

    const description = document.querySelector('meta[name="description"]');
    if (description && texts["meta.description"]) {
        description.setAttribute("content", texts["meta.description"]);
    }

    document.querySelectorAll("[data-language-select]").forEach((select) => {
        select.value = active;
    });

    return active;
}
